#!/usr/bin/env python3
"""style_lint.py 的检测规则定义（纯正则，零依赖）。

拆出本模块以满足「单文件 <=300 行」的项目规约。每条规则的含义与出处见 docstring 注释。
"""
from __future__ import annotations

import re


# --- 检测规则 ---------------------------------------------------------------

# 1) 装饰符号 / emoji（含变体选择符），刻意排除 → ← ↑ ↓ 等可能表意合法的箭头
_DECOR_CURATED = "✅⚠❌🔥✨📌💡🚀🎯❗❓⭐⚡❤➕➖"
_DECOR_RE = re.compile(
    "[" + _DECOR_CURATED + "\u2705\u274c\u2757\u2728\u2049"
    "\U0001F300-\U0001FAFF"          # 图示/表情大区
    "\ufeff\u200b"                   # 零宽字符
    "]\ufe0f?"                       # 允许尾随变体选择符
)

# 2) 套话/口号式小标题、3) 修辞反转、4) 比喻化营销措辞、5) 空话连接词、6) 空洞断言
_SLOGAN_RE = re.compile(
    r"(一句话(结论|总结|概览|作用)|划重点|兜底证据|隐藏冠军|常青|"
    r"干货|避坑指南|保姆级|手把手|一文看懂|看完这篇|收藏级)"
)
# 反转句式允许中间出现逗号/顿号/加粗标记与空格（中文最常见写法是「不是 X，而是 Y」），
# 但不得跨句（遇句末标点即停），且长度受限以抑制误报。
#
# 2026-09-30 扩展：原规则只拦「不是…而是」「并非…而是」「与其说…不如说」三种显式对仗。
# 但「而非…」「而不是…」是同一毛病的省略式——同样是在打倒一个多数情况并不存在的靶子
# （用户反馈：多数情况下并没有「而是」这个选项）。这类句式只有在**确实存在被否定的备选
# 主张**、且该否定有证据支撑时才成立，否则属于用修辞冒充论证。故一并纳入 error 级检查。
#
# 2026-10-01 扩展：再补一类「裸否定」——`不是 X` / `并非 X` 而句中并无 `而是`。
# 仍属否定式，同样犯「造靶 + 位置错配」两个毛病。
#
# 对比句式：AGENTS.md 规定「不是 X 而是 Y」「而非」「而不是」「与其说…不如说…」一律尽量不用——
# 多数情况下并不存在真实的 Y 备选，对仗只是制造对比效果，等于给读者树一个并不存在的靶子。
_GAP = r"[^。！？；\n]{1,30}?"
_INVERSION_RE = re.compile(
    r"(不是" + _GAP + r"而是|"
    r"并非" + _GAP + r"而是|"
    r"与其说" + _GAP + r"不如说|"
    r"而非|而不是|"
    r"[，。；：、]不是|^不是|并非)"          # 裸否定（无「而是」）
)
_METAPHOR_RE = re.compile(
    r"(重灾区|之谜|体温计|水位计|烧起来|风向标|晴雨表|天花板|护城河|隐形冠军|黑马)"
)
# 类比类动词/短语：用物理或生物动作描述市场现象，属营销化表达，应改中性技术动词。
# 分两档：error = 明显的营销化类比；warn = 边界词（可能另有字面义，需人工判断）。
# 注意：不收录「暴涨/暴跌/回落」等已是通用的市场中性词；也不收录媒体标题里的「高烧」
# （那是对外部标题的引用，不是本文措辞）。
_ANALOGY_STRONG_RE = re.compile(
    r"(掐断|挤爆|烧[\"'“”「」]?起来|水涨船高|撑起|引爆|点燃|井喷|熄火|狂奔|"
    r"吞噬|虹吸|回炉|裸奔|站岗|腰斩|蒸发|长出|输血|抽血|供血|拉爆|吹大)"
)
_ANALOGY_SOFT_RE = re.compile(r"(踩踏|卡位|崩塌|断崖)")
# 外部来源清单（「## 9. 信息来源」及其后）里是他人标题的引用，不算本文措辞，跳过类比检查
_SOURCE_HEADING_RE = re.compile(r"^#{1,4}\s*9[\.、]?\s*信息来源")
# 「专利」在专利数据库/服务语境下是名词（如「全球专利」「专利数据库」「公司的专利」），不是比喻。
# 比喻用法只出现在「是/成为/属于 …的专利」这类判定结构里（"溢价是跨境品种的专利"），
# 因此只在该结构下才报；「X 公司的专利」等字面领属一律不报，避免误报。
_PATENT_METAPHOR_RE = re.compile(
    r"(是|成了|成为|属于)[^。，；\n]{0,10}?的[\"'“”「」]?专利")
_EMPTY_CONNECT_RE = re.compile(
    r"(综上所述|总而言之|总的来说|值得注意的是|需要注意的是|不难看出|由此可见)"
)
_UNTESTABLE_RE = re.compile(
    r"(显然|众所周知|无疑|必然是|毋庸置疑|不言而喻|毫无疑问)"
)
_ENUM_TOKENS = ["首先", "其次", "再次", "最后"]

# 命中的严重度：error = 必改；warn = 需人工复核
_RULES = [
    ("emoji", _DECOR_RE, "error", "删除 emoji/装饰符号，改为中性文字"),
    ("slogan", _SLOGAN_RE, "error", "口号式小标题/措辞，改为陈述性标题"),
    ("inversion", _INVERSION_RE, "error",
     "对比句式（不是 X 而是 Y / 而非 / 而不是），多数并不存在真实的 Y 备选；"
     "直接陈述事实并给证据"),
    ("metaphor", _METAPHOR_RE, "error", "比喻化营销措辞，改为中性技术表述"),
    ("untestable", _UNTESTABLE_RE, "error", "无法回溯的断言，删去或改为可验证陈述"),
    ("analogy_verb", _ANALOGY_STRONG_RE, "error",
     "类比类动词（营销化表达），改为中性技术动词，如「暂停/切断/上升」"),
    ("analogy_verb", _ANALOGY_SOFT_RE, "warn",
     "可能是类比动词，若非行业通用术语（如「技术卡位」）建议改中性表述"),
    ("empty_conn", _EMPTY_CONNECT_RE, "warn", "空话连接词，考虑直接删除"),
    # 「X 不是原因，Y 才是」/「不是…，是…」：与 inversion 同族（否定式对比），
    # 只是把「而是」换成了「，是」。同属造靶/位置错配，报 warn 交人工判断。
    ("bare_negation", re.compile(r"(不是[^。！？\n]{0,20}[，,][^。！？\n]{0,12}?是)"), "warn",
     "否定式对比（不是…，是…），与『不是 X 而是 Y』同族；直接陈述正面结论即可"),
]

# 位置错配：AGENTS.md 指出「否定/对比句式若出现在**章节开头或概念首次出现处**，
# 读者脑中还没有那个念头，否定就没有着落点」。这里只对「小节首个正文句」判定：
# 即紧跟在标题（# 开头）之后的第一句，或全文首个正文句。
_OPENING_NEG_RE = re.compile(r"^[^。！？\n]{0,16}?(?:不是|并非|而非|而不是|与其说)")
